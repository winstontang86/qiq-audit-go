func TestPhysicalLines(t *testing.T) {
	cases := []struct {
		name string
		src  string
		want int
	}{
		{
			name: "empty", src: "", want: 0,
		},
		{
			name: "no_newline", src: "package p", want: 1,
		},
		{
			name: "trailing_newline", src: "package p\n", want: 1,
		},
		{
			name: "blank_line", src: "package p\n\n", want: 2,
		},
		{
			name: "crlf", src: "package p\r\n\r\n", want: 2,
		},
		{
			name: "800_lines", src: strings.Repeat("\n", 800), want: 800,
		},
		{
			name: "1600_lines", src: strings.Repeat("\n", 1600), want: 1600,
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			if got := physicalLines([]byte(tc.src)); got != tc.want {
				t.Fatalf("got %d lines, want %d", got, tc.want)
			}
		})
	}
}

func TestFunctionAndSymbolIndex(t *testing.T) {
	src := `package demo

type Box[T any] struct {
	Value T
}

type Reader interface {
	Read(p []byte) (int, error)
}

func (b *Box[T]) Get(a, c int, rest ...string) (x, y int, err error) {
	var answer int
	func() {
		func() { answer++ }()
	}()
	return answer, 0, nil
}
`
	result := indexSource("sample.go", []byte(src), 14)
	if result.Error != "" {
		t.Fatal(result.Error)
	}
	if result.Package != "demo" || result.PackageLine != 1 || result.LineCount != 17 {
		t.Fatalf("incorrect file metadata: %+v", result)
	}
	if len(result.Functions) != 3 {
		t.Fatalf("got %d functions, want 3", len(result.Functions))
	}
	method := result.Functions[0]
	if method.Name != "(*Box[T]).Get" || method.Receiver != "*Box[T]" || method.LineStart != 11 || method.LineEnd != 17 {
		t.Fatalf("incorrect method: %+v", method)
	}
	if method.BodyLines != 5 || method.InputCount != 3 || method.ResultCount != 3 {
		t.Fatalf("incorrect function counts: %+v", method)
	}
	wantClosure := "(*Box[T]).Get.func@L13C2.func@L14C3"
	if result.Functions[2].Name != wantClosure || result.Functions[2].BodyLines != 0 {
		t.Fatalf("incorrect closure: %+v", result.Functions[2])
	}
	if result.Location == nil || !result.Location.Ambiguous || len(result.Location.Candidates) != 3 {
		t.Fatalf("nested closures on a query line should require source verification: %+v", result.Location)
	}
	found := map[string]symbolInfo{}
	for _, symbol := range result.Symbols {
		found[symbol.Name] = symbol
	}
	if found["Box.Value"].Kind != "field" || found["Reader.Read"].Kind != "interface_method" {
		t.Fatalf("missing field or interface method: %+v", result.Symbols)
	}
	if found["answer"].Function != "(*Box[T]).Get" || found["answer"].Kind != "var" {
		t.Fatalf("incorrect local declaration: %+v", found["answer"])
	}
}

func TestPhysicalPositionsIgnoreLineDirectives(t *testing.T) {
	src := "package p\n//line virtual.go:900\nfunc F() {\n\tprintln(1)\n}\n"
	result := indexSource("real.go", []byte(src), 4)
	if result.Error != "" {
		t.Fatal(result.Error)
	}
	if result.Functions[0].LineStart != 3 || result.Functions[0].LineEnd != 5 || result.Location.Symbol != "F" {
		t.Fatalf("line directive altered physical positions: %+v", result)
	}
}

func TestGeneratedMarker(t *testing.T) {
	cases := []struct {
		src  string
		want bool
	}{
		{
			src: "// Code generated by example. DO NOT EDIT.\npackage p\n", want: true,
		},
		{
			src: "package p\n// Code generated by example. DO NOT EDIT.\n", want: false,
		},
		{
			src: "package p\nconst s = \"// Code generated by example. DO NOT EDIT.\"\n", want: false,
		},
		{
			src: "/* Code generated by example. DO NOT EDIT. */\npackage p\n", want: false,
		},
		{
			src: "// Code generated by example.\npackage p\n", want: false,
		},
	}
	for i, tc := range cases {
		t.Run(fmt.Sprint(i), func(t *testing.T) {
			result := indexSource("sample.pb.go", []byte(tc.src), 0)
			if result.Error != "" {
				t.Fatal(result.Error)
			}
			if result.Generated != tc.want {
				t.Fatalf("generated = %v, want %v", result.Generated, tc.want)
			}
		})
	}
}

func TestBodyLengthBoundaries(t *testing.T) {
	for _, lines := range []int{0, 20, 21, 80, 81, 160, 161} {
		t.Run(fmt.Sprint(lines), func(t *testing.T) {
			src := "package p\nfunc F() {\n" + strings.Repeat("// body\n", lines) + "}\n"
			result := indexSource("sample_test.go", []byte(src), 0)
			if result.Error != "" {
				t.Fatal(result.Error)
			}
			if result.Functions[0].BodyLines != lines {
				t.Fatalf("body lines = %d, want %d", result.Functions[0].BodyLines, lines)
			}
		})
	}
}

func TestDeclarationLocations(t *testing.T) {
	src := "package p\ntype T struct {\n\tX int\n}\nconst C = 1\nvar F = func() {}\n"
	for query, want := range map[int]string{
		1: "<package p>", 2: "T", 3: "T.X", 5: "C", 6: "<package p>.func@L6C9",
	} {
		result := indexSource("sample.go", []byte(src), query)
		if result.Error != "" || result.Location == nil || result.Location.Symbol != want {
			t.Fatalf("line %d: got %+v, want %s", query, result, want)
		}
	}
	result := indexSource("sample.go", []byte(src), 7)
	if result.Error == "" {
		t.Fatal("out-of-range line should fail")
	}
	broken := indexSource("broken.go", []byte("package p\nfunc {"), 0)
	if broken.Error == "" || len(broken.Functions) != 0 {
		t.Fatal("invalid syntax must not produce a success-looking partial index")
	}
}

func TestRunReadOnlyAndFailures(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "sample.go")
	src := []byte("package p\nfunc F() {}\n")
	if err := os.WriteFile(path, src, 0600); err != nil {
		t.Fatal(err)
	}
	var output bytes.Buffer
	if code := run([]string{"--", "-line", "2", path}, &output, io.Discard); code != 0 {
		t.Fatalf("run failed: %d: %s", code, output.String())
	}
	var decoded []fileInfo
	if err := json.Unmarshal(output.Bytes(), &decoded); err != nil {
		t.Fatal(err)
	}
	if len(decoded) != 1 || decoded[0].Location.Symbol != "F" {
		t.Fatalf("unexpected JSON: %s", output.String())
	}
	after, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(after, src) {
		t.Fatal("source file changed")
	}
	for _, args := range [][]string{nil, {"-line", "-1", path}, {"-line", "1", path, path}} {
		if code := run(args, io.Discard, io.Discard); code != 2 {
			t.Fatalf("args %v: exit = %d, want 2", args, code)
		}
	}
	missing := filepath.Join(dir, "missing.go")
	output.Reset()
	if code := run([]string{path, missing}, &output, io.Discard); code != 1 {
		t.Fatalf("missing file exit = %d, want 1", code)
	}
	if err := json.Unmarshal(output.Bytes(), &decoded); err != nil {
		t.Fatal(err)
	}
	if len(decoded) != 2 || decoded[1].Error == "" {
		t.Fatalf("missing file should remain visible in JSON: %s", output.String())
	}
	if code := run([]string{dir}, io.Discard, io.Discard); code != 1 {
		t.Fatalf("directory exit = %d, want 1", code)
	}
	link := filepath.Join(dir, "link.go")
	if err := os.Symlink(path, link); err != nil {
		t.Skipf("symlink unavailable: %v", err)
	}
	if code := run([]string{link}, io.Discard, io.Discard); code != 1 {
		t.Fatalf("symlink exit = %d, want 1", code)
	}
}

func TestSameLineClosuresAreUnambiguousInIndex(t *testing.T) {
	src := "package p\nfunc F() { func() {}(); func() {}(); println(1) }\n"
	result := indexSource("sample.go", []byte(src), 2)
	if result.Error != "" {
		t.Fatal(result.Error)
	}
	if len(result.Functions) != 3 {
		t.Fatalf("want outer function and two closures: %+v", result.Functions)
	}
	first, second := result.Functions[1], result.Functions[2]
	if first.Name == second.Name || first.ColumnStart >= second.ColumnStart {
		t.Fatalf("same-line closures must have unique positions: %+v, %+v", first, second)
	}
	if result.Location == nil || !result.Location.Ambiguous || result.Location.Symbol != "" {
		t.Fatalf("line-only query must not guess a closure: %+v", result.Location)
	}
	if len(result.Location.Candidates) != 3 {
		t.Fatalf("expected all three line candidates: %+v", result.Location)
	}
}
